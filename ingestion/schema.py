# ---------------------------------------------------------------------------
# VALIDATION MODES
# ---------------------------------------------------------------------------

class ValidationMode:
    """Validation policy applied after provider normalization.

    STRICT drops anomalous events from canonical output while persisting the
    rejected audit row. LOOSE persists the audit row and keeps the event with
    NormFlags.N_VALIDATION_ANOMALY set.
    """

    STRICT : Final[str] = "STRICT"
    LOOSE  : Final[str] = "LOOSE"


# ---------------------------------------------------------------------------
# PATH HELPERS
# ---------------------------------------------------------------------------

def normalized_path(
    base_dir: Path,
    provider: str,
    venue: str,
    product: str,
    contract: str,
    year: int,
    month: int,
    date_str: str,
    suffix: str = "mbo",
) -> Path:
    """Build the canonical normalized Parquet path."""
    return (
        base_dir
        / f"provider={provider}"
        / f"venue={venue}"
        / f"product={product}"
        / f"contract={contract}"
        / f"year={year}"
        / f"month={month:02d}"
        / f"{contract}_{date_str}_{suffix}.parquet"
    )


def reconstructed_path(
    base_dir: Path,
    provider: str,
    venue: str,
    product: str,
    contract: str,
    year: int,
    month: int,
    date_str: str,
    schema: str,
) -> Path:
    """Build the canonical reconstructed Parquet path."""
    return (
        base_dir
        / f"provider={provider}"
        / f"venue={venue}"
        / f"product={product}"
        / f"contract={contract}"
        / f"year={year}"
        / f"month={month:02d}"
        / f"{contract}_{date_str}_{schema}.parquet"
    )


def rejected_path(
    base_dir: Path,
    provider: str,
    venue: str,
    product: str,
    contract: str,
    year: int,
    month: int,
    date_str: str,
) -> Path:
    """Build the per-session rejected-event audit path."""
    return (
        base_dir
        / f"provider={provider}"
        / f"venue={venue}"
        / f"product={product}"
        / f"contract={contract}"
        / f"year={year}"
        / f"month={month:02d}"
        / f"{contract}_{date_str}_rejected.parquet"
    )
