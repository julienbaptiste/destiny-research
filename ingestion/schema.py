"""
schema.py — canonical normalized MBO schema and shared constants.

This module is the single source of truth for the provider-neutral event
contract consumed by validation, reconstruction, research features and future
trading code.

Design rules:
    - prices are fixed-point int64 at scale 1e9;
    - provider/control flags preserve Databento-compatible bit assignments;
    - normalization provenance is carried separately in norm_flags;
    - sequence preserves provider sequence, subsequence orders normalized rows
      deterministically inside one provider sequence.
"""

from __future__ import annotations

from enum import IntFlag
from pathlib import Path
from typing import Final

import pyarrow as pa


# ---------------------------------------------------------------------------
# PRICE CONSTANTS
# ---------------------------------------------------------------------------

FIXED_PRICE_SCALE: Final[int] = 1_000_000_000
UNDEF_PRICE: Final[int] = 9_223_372_036_854_775_807


# ---------------------------------------------------------------------------
# PROVIDER / CONTROL FLAGS
# ---------------------------------------------------------------------------

class Flags(IntFlag):
    """Canonical provider/control flags.

    Bit assignments intentionally follow Databento's record flags. Internal
    normalization state must never reuse these bits; use NormFlags instead.
    """

    F_LAST               = 0x80
    F_TOB                = 0x40
    F_SNAPSHOT           = 0x20
    F_MBP                = 0x10
    F_BAD_TS_RECV        = 0x08
    F_MAYBE_BAD_BOOK     = 0x04
    F_PUBLISHER_SPECIFIC = 0x02
    # 0x01 is intentionally left unassigned by the canonical contract.


class NormFlags(IntFlag):
    """Normalization/provenance flags generated by Destiny.

    These flags describe how a canonical row was produced. They are orthogonal
    to exchange/provider control flags and therefore live in a separate uint16
    column.
    """

    NONE                 = 0x0000
    N_SYNTHETIC          = 0x0001
    N_REPAIRED           = 0x0002
    N_COARSE_TS          = 0x0004
    N_VALIDATION_ANOMALY = 0x0008
    N_INFERRED_SIDE      = 0x0010
    N_INFERRED_SIZE      = 0x0020


# ---------------------------------------------------------------------------
# ACTION / SIDE ENUMS
# ---------------------------------------------------------------------------

class Action:
    """Provider-neutral MBO action names."""

    ADD    : Final[str] = "ADD"
    CANCEL : Final[str] = "CANCEL"
    MODIFY : Final[str] = "MODIFY"
    CLEAR  : Final[str] = "CLEAR"
    TRADE  : Final[str] = "TRADE"
    FILL   : Final[str] = "FILL"
    NONE   : Final[str] = "NONE"

    BOOK_ACTIONS : Final[frozenset[str]] = frozenset({ADD, CANCEL, MODIFY, CLEAR})
    ORDER_ID_REQUIRED : Final[frozenset[str]] = frozenset({ADD, CANCEL, MODIFY})
    PRICE_REQUIRED : Final[frozenset[str]] = frozenset({ADD, MODIFY})
    SIZE_REQUIRED : Final[frozenset[str]] = frozenset({ADD, MODIFY})

    DATABENTO_MAP : Final[dict[str, str]] = {
        "A": ADD,
        "C": CANCEL,
        "M": MODIFY,
        "R": CLEAR,
        "T": TRADE,
        "F": FILL,
        "N": NONE,
    }


class Side:
    """Provider-neutral side names with action-dependent semantics."""

    BID  : Final[str] = "BID"
    ASK  : Final[str] = "ASK"
    NONE : Final[str] = "NONE"

    ORDER_SIDES : Final[frozenset[str]] = frozenset({BID, ASK})

    DATABENTO_MAP : Final[dict[str, str]] = {
        "B": BID,
        "A": ASK,
        "N": NONE,
    }


